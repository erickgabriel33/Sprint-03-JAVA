-- ---------------------------------------------------------------------
-- 0. LIMPEZA (ignora erro caso a tabela ainda nao exista)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('T_REUNIA_ANALISE', 'T_REUNIA_TRANSCRICAO',
                                   'T_REUNIA_REUNIAO', 'T_REUNIA_CLIENTE',
                                   'T_REUNIA_USUARIO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

