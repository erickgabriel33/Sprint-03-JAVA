-- Usuarios da plataforma (vendedores, analistas de CS, gestores)
CREATE TABLE T_REUNIA_USUARIO (
    id_usuario   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_usuario   VARCHAR2(100) NOT NULL,
    ds_email     VARCHAR2(120) NOT NULL,
    ds_senha     VARCHAR2(200) NOT NULL,
    ds_cargo     VARCHAR2(60),
    nm_empresa   VARCHAR2(80),
    dt_cadastro  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reunia_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT un_reunia_usuario_email UNIQUE (ds_email)
);

COMMENT ON TABLE  T_REUNIA_USUARIO IS 'Usuarios que registram e analisam reunioes na plataforma Reun.IA';
COMMENT ON COLUMN T_REUNIA_USUARIO.id_usuario IS 'Identificador do usuario (identity)';
COMMENT ON COLUMN T_REUNIA_USUARIO.nm_usuario IS 'Nome completo do usuario';
COMMENT ON COLUMN T_REUNIA_USUARIO.ds_email IS 'E-mail corporativo, usado como login (unico)';
COMMENT ON COLUMN T_REUNIA_USUARIO.ds_senha IS 'Hash SHA-256 com salt da senha (formato salt:hash)';
COMMENT ON COLUMN T_REUNIA_USUARIO.ds_cargo IS 'Cargo do usuario (ex.: Executivo de Vendas, Analista de CS)';
COMMENT ON COLUMN T_REUNIA_USUARIO.nm_empresa IS 'Empresa/unidade a qual o usuario pertence';
COMMENT ON COLUMN T_REUNIA_USUARIO.dt_cadastro IS 'Data/hora do cadastro';

-- Clientes da TOTVS que participam das reunioes
CREATE TABLE T_REUNIA_CLIENTE (
    id_cliente    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_cliente    VARCHAR2(120) NOT NULL,
    nr_cnpj       CHAR(14) NOT NULL,
    ds_segmento   VARCHAR2(60) NOT NULL,
    ds_porte      VARCHAR2(10) NOT NULL,
    ds_email_contato VARCHAR2(120),
    dt_cadastro   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reunia_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT un_reunia_cliente_cnpj UNIQUE (nr_cnpj),
    CONSTRAINT ck_reunia_cliente_porte CHECK (ds_porte IN ('PEQUENO', 'MEDIO', 'GRANDE'))
);

COMMENT ON TABLE  T_REUNIA_CLIENTE IS 'Empresas clientes (ou prospects) da TOTVS';
COMMENT ON COLUMN T_REUNIA_CLIENTE.id_cliente IS 'Identificador do cliente (identity)';
COMMENT ON COLUMN T_REUNIA_CLIENTE.nm_cliente IS 'Razao social / nome fantasia';
COMMENT ON COLUMN T_REUNIA_CLIENTE.nr_cnpj IS 'CNPJ somente com numeros (unico)';
COMMENT ON COLUMN T_REUNIA_CLIENTE.ds_segmento IS 'Segmento de atuacao (Varejo, Industria, Logistica...)';
COMMENT ON COLUMN T_REUNIA_CLIENTE.ds_porte IS 'Porte da empresa: PEQUENO, MEDIO ou GRANDE';
COMMENT ON COLUMN T_REUNIA_CLIENTE.ds_email_contato IS 'E-mail do contato principal no cliente';
COMMENT ON COLUMN T_REUNIA_CLIENTE.dt_cadastro IS 'Data/hora do cadastro';

-- Reunioes de Vendas e de Customer Success (heranca em tabela unica)
CREATE TABLE T_REUNIA_REUNIAO (
    id_reuniao        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        NUMBER NOT NULL,
    id_cliente        NUMBER NOT NULL,
    ds_titulo         VARCHAR2(150) NOT NULL,
    dt_reuniao        TIMESTAMP NOT NULL,
    nr_duracao_min    NUMBER(4) NOT NULL,
    tp_reuniao        VARCHAR2(10) NOT NULL,
    st_reuniao        VARCHAR2(10) DEFAULT 'AGENDADA' NOT NULL,
    fl_processada     CHAR(1) DEFAULT 'N' NOT NULL,
    vl_oportunidade   NUMBER(14,2),
    nr_score_risco    NUMBER(3),
    fl_concorrente    CHAR(1),
    nr_nps            NUMBER(2),
    nr_reclamacoes    NUMBER(4),
    fl_sinal_churn    CHAR(1),
    CONSTRAINT pk_reunia_reuniao PRIMARY KEY (id_reuniao),
    CONSTRAINT fk_reuniao_usuario FOREIGN KEY (id_usuario) REFERENCES T_REUNIA_USUARIO (id_usuario),
    CONSTRAINT fk_reuniao_cliente FOREIGN KEY (id_cliente) REFERENCES T_REUNIA_CLIENTE (id_cliente),
    CONSTRAINT un_reunia_reuniao_agenda UNIQUE (id_cliente, dt_reuniao),
    CONSTRAINT ck_reuniao_duracao CHECK (nr_duracao_min BETWEEN 1 AND 1440),
    CONSTRAINT ck_reuniao_tipo CHECK (tp_reuniao IN ('VENDAS', 'CS')),
    CONSTRAINT ck_reuniao_status CHECK (st_reuniao IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
    CONSTRAINT ck_reuniao_processada CHECK (fl_processada IN ('S', 'N')),
    CONSTRAINT ck_reuniao_concorrente CHECK (fl_concorrente IN ('S', 'N')),
    CONSTRAINT ck_reuniao_churn CHECK (fl_sinal_churn IN ('S', 'N')),
    CONSTRAINT ck_reuniao_risco CHECK (nr_score_risco BETWEEN 0 AND 100),
    CONSTRAINT ck_reuniao_nps CHECK (nr_nps BETWEEN 0 AND 10),
    CONSTRAINT ck_reuniao_valor CHECK (vl_oportunidade >= 0)
);

COMMENT ON TABLE  T_REUNIA_REUNIAO IS 'Reunioes comerciais. VENDAS usa colunas de oportunidade; CS usa colunas de satisfacao';
COMMENT ON COLUMN T_REUNIA_REUNIAO.id_reuniao IS 'Identificador da reuniao (identity)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.id_usuario IS 'FK - usuario responsavel pela reuniao';
COMMENT ON COLUMN T_REUNIA_REUNIAO.id_cliente IS 'FK - cliente participante';
COMMENT ON COLUMN T_REUNIA_REUNIAO.ds_titulo IS 'Titulo/assunto da reuniao';
COMMENT ON COLUMN T_REUNIA_REUNIAO.dt_reuniao IS 'Data e hora da reuniao';
COMMENT ON COLUMN T_REUNIA_REUNIAO.nr_duracao_min IS 'Duracao em minutos (1 a 1440)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.tp_reuniao IS 'Tipo: VENDAS ou CS (Customer Success)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.st_reuniao IS 'Status: AGENDADA, REALIZADA ou CANCELADA';
COMMENT ON COLUMN T_REUNIA_REUNIAO.fl_processada IS 'S quando a transcricao ja foi analisada pela IA';
COMMENT ON COLUMN T_REUNIA_REUNIAO.vl_oportunidade IS 'VENDAS - valor estimado da oportunidade (R$)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.nr_score_risco IS 'VENDAS - risco de perda da negociacao (0 a 100)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.fl_concorrente IS 'VENDAS - S se houve mencao a concorrente';
COMMENT ON COLUMN T_REUNIA_REUNIAO.nr_nps IS 'CS - nota NPS informada pelo cliente (0 a 10)';
COMMENT ON COLUMN T_REUNIA_REUNIAO.nr_reclamacoes IS 'CS - quantidade de reclamacoes registradas';
COMMENT ON COLUMN T_REUNIA_REUNIAO.fl_sinal_churn IS 'CS - S se ha sinal de cancelamento (churn)';

-- Transcricao (texto) de cada reuniao - 1 para 1
CREATE TABLE T_REUNIA_TRANSCRICAO (
    id_transcricao  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reuniao      NUMBER NOT NULL,
    ds_texto        CLOB NOT NULL,
    nr_palavras     NUMBER(7) NOT NULL,
    dt_envio        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reunia_transcricao PRIMARY KEY (id_transcricao),
    CONSTRAINT fk_transcricao_reuniao FOREIGN KEY (id_reuniao)
        REFERENCES T_REUNIA_REUNIAO (id_reuniao) ON DELETE CASCADE,
    CONSTRAINT un_transcricao_reuniao UNIQUE (id_reuniao)
);

COMMENT ON TABLE  T_REUNIA_TRANSCRICAO IS 'Texto transcrito de cada reuniao (uma transcricao por reuniao)';
COMMENT ON COLUMN T_REUNIA_TRANSCRICAO.id_transcricao IS 'Identificador da transcricao (identity)';
COMMENT ON COLUMN T_REUNIA_TRANSCRICAO.id_reuniao IS 'FK - reuniao transcrita (unica)';
COMMENT ON COLUMN T_REUNIA_TRANSCRICAO.ds_texto IS 'Conteudo integral da transcricao';
COMMENT ON COLUMN T_REUNIA_TRANSCRICAO.nr_palavras IS 'Quantidade de palavras do texto';
COMMENT ON COLUMN T_REUNIA_TRANSCRICAO.dt_envio IS 'Data/hora do envio da transcricao';

-- Resultado da analise automatica da transcricao - 1 para 1
CREATE TABLE T_REUNIA_ANALISE (
    id_analise          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reuniao          NUMBER NOT NULL,
    ds_sentimento       VARCHAR2(10) NOT NULL,
    nr_score_sentimento NUMBER(4) NOT NULL,
    nr_risco_churn      NUMBER(3) NOT NULL,
    nr_score_oportunidade NUMBER(3) NOT NULL,
    ds_produtos         VARCHAR2(300),
    ds_concorrentes     VARCHAR2(300),
    ds_termos           VARCHAR2(300),
    ds_recomendacao     VARCHAR2(1000) NOT NULL,
    dt_analise          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reunia_analise PRIMARY KEY (id_analise),
    CONSTRAINT fk_analise_reuniao FOREIGN KEY (id_reuniao)
        REFERENCES T_REUNIA_REUNIAO (id_reuniao) ON DELETE CASCADE,
    CONSTRAINT un_analise_reuniao UNIQUE (id_reuniao),
    CONSTRAINT ck_analise_sentimento CHECK (ds_sentimento IN ('POSITIVO', 'NEUTRO', 'NEGATIVO')),
    CONSTRAINT ck_analise_score_sent CHECK (nr_score_sentimento BETWEEN -100 AND 100),
    CONSTRAINT ck_analise_churn CHECK (nr_risco_churn BETWEEN 0 AND 100),
    CONSTRAINT ck_analise_oport CHECK (nr_score_oportunidade BETWEEN 0 AND 100)
);

COMMENT ON TABLE  T_REUNIA_ANALISE IS 'Indicadores gerados automaticamente a partir da transcricao';
COMMENT ON COLUMN T_REUNIA_ANALISE.id_analise IS 'Identificador da analise (identity)';
COMMENT ON COLUMN T_REUNIA_ANALISE.id_reuniao IS 'FK - reuniao analisada (unica)';
COMMENT ON COLUMN T_REUNIA_ANALISE.ds_sentimento IS 'Sentimento geral: POSITIVO, NEUTRO ou NEGATIVO';
COMMENT ON COLUMN T_REUNIA_ANALISE.nr_score_sentimento IS 'Score de sentimento de -100 (negativo) a 100 (positivo)';
COMMENT ON COLUMN T_REUNIA_ANALISE.nr_risco_churn IS 'Risco de churn/insatisfacao (0 a 100)';
COMMENT ON COLUMN T_REUNIA_ANALISE.nr_score_oportunidade IS 'Potencial de oportunidade comercial (0 a 100)';
COMMENT ON COLUMN T_REUNIA_ANALISE.ds_produtos IS 'Produtos TOTVS mencionados, separados por virgula';
COMMENT ON COLUMN T_REUNIA_ANALISE.ds_concorrentes IS 'Concorrentes mencionados, separados por virgula';
COMMENT ON COLUMN T_REUNIA_ANALISE.ds_termos IS 'Principais termos encontrados, separados por virgula';
COMMENT ON COLUMN T_REUNIA_ANALISE.ds_recomendacao IS 'Recomendacao de acao para a area comercial';
COMMENT ON COLUMN T_REUNIA_ANALISE.dt_analise IS 'Data/hora em que a analise foi gerada';

